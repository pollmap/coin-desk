export function guideReading(id: string): GuideReading {
  const entry = readings[id];
  if (!entry) throw new Error(`Missing beginner reading: ${id}`);
  return { meaning: entry[0], lookFor: entry[1], distinction: entry[2] };
}
export const REVIEWED_GUIDE_IDS = Object.keys(readings);

export function readingLesson(article: GuideArticle, asset: Asset): GuideLesson {
  const lesson = guideLesson(article);
  const definition = article.id === 'net-hashrate' ? networkMetric(asset, 'hashrate') : undefined;
  if (!definition) return lesson;
  const scale = definition.unit === 'GH/s' ? '10⁹' : '10¹²';
  return {
    ...lesson,
    method: [definition.formula, `1 ${definition.unit} = 초당 ${scale} 해시`],
    example: [`2 ${definition.unit}는 초당 2 × ${scale}회의 해시 계산을 뜻합니다.`],
    conclusion:
      '선택 네트워크의 채굴 연산량 추정치입니다. 해시 함수가 다른 코인의 수치 크기나 보안을 직접 비교하지 않습니다.',
  };
}
